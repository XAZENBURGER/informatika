// ============================================================
// Лабораторная работа 5. Табуляция заданной функции.
// Вариант 6.
//
// Задание: вывести значения функции
//     f(x) = e^Y - 1000 * Y
// в точках x = n/2 - 1, где n = 0, 1, ..., 32,   Y = [x] - x,
// где [x] — целая часть числа x (функция floor из <cmath>).
//
// Критерии полноты:
//   1. Функция f реализована отдельно (см. double f(double x)).
//   2. Табуляция — циклом со счётчиком n.
//   3. Повторяющееся подвыражение [x] вычисляется ОДНАЖДЫ и
//      сохраняется в константу intpart; затем Y = intpart - x.
//      (Если бы написали floor(x) дважды — одно и то же считалось
//       бы два раза, что запрещено критерием.)
//
// Замечание про точность: n/2 при чётных n даёт точные целые x
// (например x = 0, 1, 2...), тогда Y = [x] - x = 0 и f = e^0 - 0 = 1.
// При нечётных n x имеет вид k + 0.5 (половина представима в двоичной
// системе точно), поэтому Y = -0.5 ровно, и f = e^-0.5 + 500.
// ============================================================

#include <iostream>    // cin, cout
#include <iomanip>     // setprecision
#include <cmath>       // exp, floor

using namespace std;

// Требуемая функция f(x).
double f(double x)
{
    double const intpart = floor(x);           // [x] — целая часть, считаем ОДИН раз
    double const Y = intpart - x;              // Y = [x] - x  (при x >= 0 это дробь, <= 0; вообще -1 < Y <= 0)
    return exp(Y) - 1000.0 * Y;                // e^Y - 1000*Y; exp — экспонента из cmath
}

int main()
{
    cout << fixed << setprecision(8);          // 8 знаков после запятой

    // Цикл со счётчиком: n пробегает значения 0, 1, ..., 32.
    for (int n = 0; n <= 32; ++n)
    {
        double const x = n / 2.0 - 1.0;        // точка табуляции: x = n/2 - 1
                                               // (2.0 — чтобы деление было вещественным!)
        cout << n << '\t' << x << '\t' << f(x) << '\n';
    }
    return 0;
}
