// ============================================================
// Лабораторная работа 5. Табуляция заданной функции.
// Вариант 4.
//
// Задание: вывести значения функции
//     f(x) = sin(Y) / (1 + cos^2(Y))            (в числителе и знаменателе — один и тот же Y)
// в точках x = n/2 + 1, где n = 0, 1, ..., 10,   Y = x^3.
//
// Критерии полноты:
//   1. Функция f реализована отдельно (см. double f(double x)).
//   2. Табуляция — циклом со счётчиком n.
//   3. Повторяющиеся подвыражения вычисляются ОДНАЖДЫ:
//        Y   = x*x*x          — один раз (это само подвыражение x^3);
//        c   = cos(Y)         — один раз, затем используем c*c
//                                (в формуле cos(Y) встречается дважды:
//                                 слагаемое cos^2(Y) строим из уже
//                                 вычисленного c).
//
// Знаменатель 1 + cos^2(Y) >= 1 всегда, поэтому деления на ноль нет.
// ============================================================

#include <iostream>    // cin, cout
#include <iomanip>     // setprecision
#include <cmath>       // sin, cos

using namespace std;

// Требуемая функция f(x).
double f(double x)
{
    double const Y = x * x * x;                // Y = x^3 — считаем ОДИН раз
    double const c = cos(Y);                   // cos(Y) — считаем ОДИН раз
    return sin(Y) * c / (1.0 + c * c);         // cos^2(Y) = c*c, повторных вызовов cos нет
}

int main()
{
    cout << fixed << setprecision(8);          // 8 знаков после запятой

    // Цикл со счётчиком: n пробегает значения 0, 1, ..., 10.
    for (int n = 0; n <= 10; ++n)
    {
        double const x = n / 2.0 + 1.0;        // точка табуляции: x = n/2 + 1
                                               // (2.0 — чтобы деление было вещественным!)
        cout << n << '\t' << x << '\t' << f(x) << '\n';
    }
    return 0;
}
