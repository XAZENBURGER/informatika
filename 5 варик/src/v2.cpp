// ============================================================
// Лабораторная работа 5. Табуляция заданной функции.
// Вариант 2.
//
// Задание: вывести значения функции
//     f(x) = Y * arctg(ln|Y|) / (1 + Y^2)      (арктангенс в радианах)
// в точках x = n/4 - 2, где n = 0, 1, ..., 16,  Y = x^2 - 1.
//
// Критерии полноты:
//   1. Функция f реализована отдельно (см. double f(double x)).
//   2. Табуляция — циклом со счётчиком n.
//   3. Повторяющееся подвыражение Y = x*x - 1 вычисляется ОДНАЖДЫ
//      внутри f и сохраняется в константу Y (а не пересчитывается
//      трижды в формуле).
//
// Примечание: при n = 4 и n = 12 получается x = -1 и x = +1,
// тогда Y = 0, ln|Y| = ln(0) = -inf, но arctg(-inf) = -pi/2 —
// конечное число, а знаменатель 1 + Y^2 = 1. Итого f = 0 * (-pi/2) = 0.
// Поэтому специальные ветки не нужны — всё считается «само».
// ============================================================

#include <iostream>    // cin, cout
#include <iomanip>     // setprecision
#include <cmath>       // fabs, log, atan, pow

using namespace std;

// Требуемая функция f(x).
double f(double x)
{
    double const Y = x * x - 1.0;              // Y = x^2 - 1 (считаем ОДИН раз!)
    return Y * atan(log(fabs(Y))) / (1.0 + Y * Y);
    //      ^^^^^^^^^^^^^^^^^^^   ^^^^^^^^^^^
    //      |                     arctg(ln|Y|) — стандартные функции из cmath:
    //      |                     log — натуральный логарифм, atan — арктангенс,
    //      |                     fabs — модуль числа
    //      Y умножается на arctg(...) и делится на (1 + Y^2)
}

int main()
{
    cout << fixed << setprecision(8);          // 8 знаков после запятой

    // Цикл со счётчиком: n пробегает значения 0, 1, ..., 16.
    for (int n = 0; n <= 16; ++n)
    {
        double const x = n / 4.0 - 2.0;        // точка табуляции: x = n/4 - 2
                                               // (4.0 — чтобы деление было вещественным!)
        cout << n << '\t' << x << '\t' << f(x) << '\n';
        //     ^   ^^^^^^   ^^^^^^
        //     |   |        значение функции
        //     |   аргумент x
        //     номер точки
    }
    return 0;
}
