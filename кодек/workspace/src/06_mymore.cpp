// ==============================================================
// ЗАДАНИЕ 13: mymore.exe — аналог команды more
// ==============================================================
// Команда more показывает текст ПОСТРАНОЧНО: выводит 24 строки,
// затем ждёт нажатия Enter (показать ещё строку) или Q (выйти).
// Используется, когда вывод программы не помещается на экран:
//     type bigfile.txt | mymore.exe
//
// Как читать по одному символу в Windows-консоли:
//   обычный cin.get ждал бы Enter после каждой клавиши (терминал
//   буферизует ввод). Функция _getch() из <conio.h> (есть ТОЛЬКО
//   в MS Visual Studio) ждёт нажатие клавиши и возвращает её код
//   СРАЗУ, без Enter — как настоящая команда more.
//
// Разбор для новичка:
//   - getline(cin, line) читает очередную строку текста;
//   - счётчик rows считает показанные строки текущей "страницы";
//   - когда rows достигает PAGE (24), печатаем приглашение --More--
//     и ждём клавишу: 'q'/'Q' -> выход, любая другая -> ещё страница.

#include <iostream>
#include <string>
using namespace std;

#ifdef _MSC_VER
#include <conio.h>       // MS Visual Studio: мгновенное чтение клавиши
inline char waitKey() { return (char)_getch(); }
#else
inline char waitKey() { char c; cin.get(c); return c; }  // переносимость
#endif

const int PAGE = 24;        // строк на "экран"

int main() {
    string line;
    int rows = 0;           // сколько строк показано с последней паузы

    while (getline(cin, line)) {
        cout << line << "\n";
        ++rows;                          // то же самое, что rows = rows + 1

        if (rows >= PAGE) {              // страница заполнена?
            cout << "--More-- press any key (q to quit): ";
            char key = waitKey();        // ждём нажатие
            cout << "\r";                // вернуть курсор в начало строки
            if (key == 'q' || key == 'Q')
                return 0;                // пользователь хочет выйти
            rows = 0;                    // новая страница
        }
    }
    return 0;                            // текст закончился
}
