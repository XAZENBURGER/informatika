// ==============================================================
// ЗАДАНИЕ 8: сравнение cin >> name и getline(cin, name)
// ==============================================================
// В этом файле ДВЕ программы сразу (переключаются параметром
// командной строки), но для отчёта можно собрать каждую отдельно.
//
// ГЛАВНОЕ ОТЛИЧИЕ:
//   cin >> name     читает ОДНО СЛОВО: останавливается на любом
//                   пробеле/табуляции/переносе строки. Фраза
//                   "Ivan Petrov Sidorov" -> в name попадёт только
//                   "Ivan", остальное останется в буфере ввода.
//
//   getline(cin,name) читает ВСЮ СТРОКУ до символа переноса строки
//                   ('\n'). Пробелы внутри строки НЕ являются
//                   разделителями. "Ivan Petrov Sidorov" -> вся
//                   фраза целиком попадёт в name.
//
// Дополнительно: после cin >> в буфере остаётся "\n". Если следом
// вызвать getline, он увидит этот пустой остаток и вернёт ПУСТУЮ
// строку — классическая ловушка новичков. Здесь мы этого не делаем,
// но имейте в виду.

#include <iostream>
#include <string>
using namespace std;

int main(int argc, char* argv[]) {
    string name;                       // пустая строка изначально

    cout << "What is your name? ";

    // Запускаем программу с параметром "getline", чтобы выбрать
    // второй вариант чтения:  str_compare.exe getline
    if (argc > 1 && string(argv[1]) == "getline") {
        // ВАРИАНТ ИЗ ПРИМЕРА 3.2: читаем всю строку целиком
        getline(cin, name);            // функция возвращает cin,
                                       // поэтому её можно ставить в условие цикла
    } else {
        // ВАРИАНТ ИЗ ПРИМЕРА 3.1: читаем только первое слово
        cin >> name;
    }

    cout << "Greetings, " << name << "\n";
    return 0;
}

