// ==============================================================
// ЗАДАНИЕ 9: unique.exe — удаление подряд идущих одинаковых СТРОК
// ==============================================================
// Программа читает строки из стандартного потока ввода (cin)
// с помощью getline и выводит их в cout, пропуская строки,
// совпадающие с предыдущей.
//
// Это строчный аналог кода из задания 7 (там были символы).
//
// Ключевые моменты для новичка:
//   getline(cin, line) возвращает объект потока cin.
//   Поток в условии = "истина", пока не достигнут конец файла.
//   Поэтому `while (getline(cin, line))` — стандартный способ
//   читать файл построчно "до упора".
//
// Проверка в командной строке (Windows):
//   unique.exe < input.txt > output.txt
//   type output.txt

#include <iostream>
#include <string>
using namespace std;

int main() {
    string prev;                        // предыдущая прочитанная строка
    bool first = true;                  // флаг: читали ли мы уже первую строку

    string line;
    // Читаем построчно, пока ввод не закончится (конец файла или Ctrl+Z)
    while (getline(cin, line)) {
        // Печатаем строку, если это первая строка ИЛИ она не равна предыдущей
        if (first || line != prev) {
            cout << line << "\n";       // вывод + перенос строки
            prev = line;                // запоминаем как предыдущую
            first = false;
        }
        // иначе — молча пропускаем повтор
    }
    return 0;
}

