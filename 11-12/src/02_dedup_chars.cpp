// ==============================================================
// ЗАДАНИЕ 7: что делает приведённый код?
// ==============================================================
// Оригинальный код из задания:
//
//     if (char prev; cin.get(prev)) {
//         cout.put(prev);
//         for (char ch; cin.get(ch);)
//             if (ch != prev)
//                 cout.put(prev = ch);
//     }
//
// ОТВЕТ: код удаляет ПОДРЯД ИДУЩИЕ повторяющиеся символы
// (схлопывает серии одинаковых символов в один).
//
// Построчное объяснение:
//
// 1) if (char prev; cin.get(prev))
//    - создаём переменную prev (предыдущий символ);
//    - cin.get(prev) читает ОДИН символ из стандартного ввода
//      и возвращает "истину", если чтение удалось.
//    - Если ввод пуст (файл пустой или сразу конец), условие
//      ложно и программа ничего не делает.
//
// 2) cout.put(prev);
//    - первый прочитанный символ всегда выводим — он unique по
//      определению (повторяться ещё не мог).
//
// 3) for (char ch; cin.get(ch);)
//    - цикл: читаем по одному символу в ch, пока чтение успешно.
//
// 4) if (ch != prev) cout.put(prev = ch);
//    - если новый символ ОТЛИЧАЕТСЯ от предыдущего — выводим его.
//    - Запись `prev = ch` одновременно присваивает ch переменной
//      prev и возвращает это же значение (значение выражения
//      присваивания == присвоенное значение). То есть:
//        prev = ch;          // запоминаем новый символ
//        cout.put(prev);     // и печатаем его
//      в одной строчке.
//    - Если ch == prev — НЕ выводим: это повтор, пропускаем.
//
// Пример: "aaabbbcccd" -> "abcd"
// Но:    "abacada"    -> "abacada" (повторы не подряд — останутся!)
//
// Программа ниже — тот же код + комментарии, чтобы можно было
// собрать её и проверить на реальном файле через перенаправление:
//     dedup_chars.exe < test.txt > out.txt

#include <iostream>
using namespace std;

int main() {
    // Читаем первый символ. Если ввод пуст — завершаемся.
    if (char prev; cin.get(prev)) {
        cout.put(prev);                    // печатаем его безусловно
        for (char ch; cin.get(ch); )       // читаем остальные по одному
            if (ch != prev)                // если не повтор предыдущего...
                cout.put(prev = ch);       // ...печатаем и запоминаем
    }
    return 0;
}
