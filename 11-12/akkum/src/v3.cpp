// Вариант 3. Сумма модулей чисел, не превосходящих по модулю единицу.
// Предикат: |x| <= 1. Действие: sum += fabs(x). Если таких чисел нет — 0.
#include <iostream>
#include <cmath>            // fabs — модуль числа
using namespace std;

int main() {
    double sum = 0;         // аккумулятор: начальное значение 0 (это и есть ответ "по умолчанию")

    // Цикл ввода: читаем числа из потока cin, пока чтение успешно.
    // Перенаправление "v3.exe < data.txt" поставляет числа из файла;
    // конец файла = условие цикла ложно = выход из цикла.
    for (double x; cin >> x; )
        if (fabs(x) <= 1)       // предикат: число не превосходит 1 по модулю
            sum += fabs(x);     // аккумуляция: добавляем модуль числа к сумме

    cout << sum << endl;    // вывод результата в стандартный поток вывода
    return 0;
}
