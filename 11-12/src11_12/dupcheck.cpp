// ==============================================================
// ЗАДАНИЕ 12: dupcheck.exe — поиск совпадающих строк через код возврата
// ==============================================================
// Программа читает строки из стандартного ввода и возвращает:
//    1 (НЕУСПЕХ), если найдены ДВЕ ПОДРЯД ИДУЩИЕ одинаковые строки;
//    0 (УСПЕХ),   если таких повторов нет.
//
// Её ставят ПОСЛЕ sort в конвейере: после сортировки все одинаковые
// строки оказываются рядом, поэтому проверки «соседей» достаточно,
// чтобы найти любой дубль в файле.
//
// Для новичка: int main() возвращает число — это «код возврата»
// (exit code). Оболочка трактует 0 как успех, любое другое число —
// как ошибку. На этом построены связки && и || (задание 11).

#include <iostream>
#include <string>
using namespace std;

int main() {
    string prev, line;

    // Читаем первую строку отдельно — её не с чем сравнить
    if (!getline(cin, prev))
        return 0;                       // ввод пуст -> повторов нет -> успех

    while (getline(cin, line)) {        // читаем остальные строки
        if (line == prev) {             // СОВПАДЕНИЕ с предыдущей!
            cerr << "Duplicate found: \"" << line << "\"\n";
            // Пишем в cerr (поток ошибок), чтобы сообщение
            // не смешивалось с данными в конвейере.
            return 1;                   // возвращаем код НЕУСПЕХА
        }
        prev = line;                    // сдвигаем «окно» сравнения
    }

    return 0;                           // дошли до конца — дублей нет, УСПЕХ
}
